const a = 3;
const b = 8;

// Arithmetic operators
const sum = a + b;
console.log(sum);

const subtraction = a - b;
console.log(subtraction);

const multiplication = a * b;
console.log(multiplication);

const devision = b / a;
console.log(devision);

// Exponentiation and modulus
const power = a ** b;
console.log(power);

const modulus = b % a;
console.log(modulus);

